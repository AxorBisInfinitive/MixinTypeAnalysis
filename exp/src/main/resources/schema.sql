CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    price DECIMAL(12, 2) NOT NULL CHECK (price >= 0),
    stock BIGINT DEFAULT 0 NOT NULL CHECK (stock BETWEEN 0 AND 1000000000),
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS sales_orders (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer VARCHAR(120) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    total DECIMAL(19, 2) NOT NULL CHECK (total >= 0),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS order_lines (
    order_id BIGINT NOT NULL REFERENCES sales_orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    sku VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    subtotal DECIMAL(19, 2) NOT NULL CHECK (subtotal >= 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity BIGINT NOT NULL CHECK (quantity <> 0),
    balance BIGINT NOT NULL CHECK (balance BETWEEN 0 AND 1000000000),
    reason VARCHAR(24) NOT NULL CHECK (reason IN ('RESTOCK', 'ORDER_CONFIRMED', 'ORDER_CANCELLED')),
    order_id BIGINT REFERENCES sales_orders(id),
    note VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (order_id, product_id, reason)
);

CREATE INDEX IF NOT EXISTS stock_movements_product_idx ON stock_movements(product_id, id);
